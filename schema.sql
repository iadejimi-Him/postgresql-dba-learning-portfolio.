-- Hospital Management Database
-- Portable schema script based on the PostgreSQL 18.6 schema export.
-- This script creates the three tables and constraints in the public schema.

CREATE TABLE public.patient (
    id integer GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1 INCREMENT BY 1 CACHE 1),
    first_name character varying NOT NULL,
    last_name character varying NOT NULL,
    email character varying,
    gender character varying NOT NULL,
    address character varying NOT NULL,
    CONSTRAINT patient_pkey PRIMARY KEY (id),
    CONSTRAINT patient_email_key UNIQUE (email)
);

CREATE TABLE public.doctors (
    id integer NOT NULL,
    first_name character varying NOT NULL,
    last_name character varying NOT NULL,
    email character varying,
    gender character varying NOT NULL,
    address character varying NOT NULL,
    CONSTRAINT doctors_pkey PRIMARY KEY (id),
    CONSTRAINT doctors_email_key UNIQUE (email)
);

CREATE TABLE public.appointments (
    id integer NOT NULL,
    patient_id integer NOT NULL,
    doctor_id integer NOT NULL,
    appointment_date timestamp without time zone NOT NULL,
    appointment_status character varying(30) NOT NULL,
    CONSTRAINT appointments_pkey PRIMARY KEY (id),
    CONSTRAINT fk_appointment_patient
        FOREIGN KEY (patient_id) REFERENCES public.patient (id),
    CONSTRAINT fk_appointment_doctor
        FOREIGN KEY (doctor_id) REFERENCES public.doctors (id)
);
